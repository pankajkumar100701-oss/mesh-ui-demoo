type Bounds = { poly: LonLat[]; minX: number; maxX: number; minY: number; maxY: number };

function withBounds(polys: LonLat[][]): Bounds[] {
  return polys.map((poly) => {
    let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
    for (const [x, y] of poly) {
      minX = Math.min(minX, x);
      maxX = Math.max(maxX, x);
      minY = Math.min(minY, y);
      maxY = Math.max(maxY, y);
    }
    return { poly, minX, maxX, minY, maxY };
  });
}

function inside(poly: LonLat[], x: number, y: number) {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

let landCache: Bounds[] | null = null;
let seaCache: Bounds[] | null = null;

/** True when the lon/lat point (degrees) is on land. Antarctica is a simple polar cap. */
export function isLand(lon: number, lat: number) {
  if (lat < -70.5) return true;
  landCache ??= withBounds(LAND);
  seaCache ??= withBounds(SEAS);
  const test = (list: Bounds[]) =>
    list.some((b) => lon >= b.minX && lon <= b.maxX && lat >= b.minY && lat <= b.maxY && inside(b.poly, lon, lat));
  return test(landCache) && !test(seaCache);
}

