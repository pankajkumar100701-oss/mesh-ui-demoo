/** Deterministic pseudo-shipment for any tracking code. */
export function lookupShipment(raw: string): Shipment | null {
  const code = raw.trim().toUpperCase();
  if (code.length < 4) return null;
  let h = 2166136261;
  for (let i = 0; i < code.length; i++) h = Math.imul(h ^ code.charCodeAt(i), 16777619) >>> 0;
  const a = h % HUBS.length;
  let b = (h >>> 8) % (HUBS.length - 1);
  if (b >= a) b += 1;
  const air = ((h >>> 16) & 3) === 0;
  return {
    code,
    from: HUBS[a].id,
    to: HUBS[b].id,
    mode: air ? "Air" : "Ocean",
    progress: 0.18 + (((h >>> 4) % 1000) / 1000) * 0.72,
    cargo: CARGO[(h >>> 12) % CARGO.length],
    days: air ? 2 + ((h >>> 20) % 3) : 14 + ((h >>> 20) % 22),
  };
}
